/* ------------------------------------------------------------------
 * Builds data/worldCities.js — the offline city list used for search
 * suggestions. Run this only when you want to refresh the list.
 *
 * 1. Download from https://download.geonames.org/export/dump/
 *      cities15000.zip  (unzip it → cities15000.txt)
 *      countryInfo.txt
 * 2. node scripts/buildWorldCities.js <cities15000.txt> <countryInfo.txt> [minPopulation]
 *
 * Data © GeoNames (CC BY 4.0) — credited in the app.
 * ------------------------------------------------------------------ */

const fs = require("fs");
const path = require("path");

const [citiesFile, countriesFile, minPopArg] = process.argv.slice(2);
if (!citiesFile || !countriesFile) {
    console.error("Usage: node scripts/buildWorldCities.js <cities15000.txt> <countryInfo.txt> [minPopulation]");
    process.exit(1);
}
const MIN_POPULATION = Number(minPopArg) || 50000;
const OUT_FILE = path.join(__dirname, "..", "data", "worldCities.js");

// countryInfo.txt: tab-separated, comment lines start with '#'. Col 0 = ISO code, col 4 = name
const countries = {};
for (const line of fs.readFileSync(countriesFile, "utf8").split("\n")) {
    if (!line || line.startsWith("#")) continue;
    const cols = line.split("\t");
    countries[cols[0]] = cols[4];
}

// cities15000.txt columns: 1 name, 2 ascii name, 4 lat, 5 lng, 7 feature code, 8 country, 14 population
const cities = [];
for (const line of fs.readFileSync(citiesFile, "utf8").split("\n")) {
    const cols = line.split("\t");
    if (cols.length < 15) continue;

    const population = Number(cols[14]);
    const featureCode = cols[7];
    if (population < MIN_POPULATION) continue;
    if (featureCode === "PPLX") continue; // city districts/neighbourhoods, not cities

    const name = cols[1];
    const ascii = cols[2] !== name ? cols[2] : ""; // only stored when different ("São Paulo" → "Sao Paulo")
    const lat = Math.round(Number(cols[4]) * 100) / 100; // ~1 km precision is plenty for weather
    const lng = Math.round(Number(cols[5]) * 100) / 100;
    cities.push({ population, row: [name, ascii, cols[8], lat, lng] });
}

// Biggest first, so when two cities match equally the larger one is suggested first
cities.sort((a, b) => b.population - a.population);

const usedCountries = {};
for (const c of cities) usedCountries[c.row[2]] = countries[c.row[2]] || c.row[2];

const out =
    `/* AUTO-GENERATED by scripts/buildWorldCities.js — do not edit by hand.\n` +
    ` * ${cities.length} cities with population >= ${MIN_POPULATION}, biggest first.\n` +
    ` * Row format: [name, asciiName (or "" if same), countryCode, lat, lng]\n` +
    ` * Data © GeoNames (geonames.org), CC BY 4.0. */\n\n` +
    `export const COUNTRIES = ${JSON.stringify(usedCountries)};\n\n` +
    `export const CITIES = [\n${cities.map((c) => JSON.stringify(c.row)).join(",\n")}\n];\n`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, out);
console.log(`Wrote ${cities.length} cities (${Math.round(out.length / 1024)} KB) → ${OUT_FILE}`);
